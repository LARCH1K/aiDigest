def guess_criterion(text: str, methodology: Methodology) -> str:
    low = text.lower().replace("ё", "е")
    for criterion, words in _KEYWORDS[methodology]:
        if any(w.replace("ё", "е") in low for w in words):
            return criterion
    return OTHER_CRITERION
